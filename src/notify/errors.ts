export type SmsMode = 'simple' | 'pattern';

/**
 * آیا پاسخ نشانه‌ی ارسال موفق است؟
 * هر دو متد در موفقیت یک `recId` بیش از ۱۵ رقم برمی‌گردانند.
 */
export function isSuccess(response: string): boolean {
  const value = response.trim();
  return /^\d+$/.test(value) && value.length > 15;
}

/** پیام فارسی متناظر با پاسخ سامانه. */
export function describeResponse(response: string, mode: SmsMode): string {
  const code = response.trim();
  if (isSuccess(code)) return `ارسال موفق (شناسه: ${code})`;

  const specific = mode === 'simple' ? SIMPLE_ONLY : PATTERN_ONLY;
  return specific[code] ?? SHARED[code] ?? `پاسخ ناشناخته از ملی پیامک: ${code}`;
}

/**
 * آیا این خطا با سوییچ به حالت الگو حل می‌شود؟
 * کد ۳۵ یعنی شماره در لیست سیاه مخابرات است و فقط خط خدماتی اشتراکی
 * می‌تواند به آن پیامک بدهد — برای اعلان «ورود به درگاه» حیاتی است.
 */
export function suggestsPatternMode(response: string, mode: SmsMode): boolean {
  return mode === 'simple' && response.trim() === '35';
}
